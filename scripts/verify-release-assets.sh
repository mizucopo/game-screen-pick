#!/bin/sh
# Validate the complete immutable asset set before upload and again after download.
set -eu
destination=$1
version=$2
commit=$3
case "$version" in ''|*[!A-Za-z0-9.+-]*) printf 'Invalid version\n' >&2; exit 1 ;; esac
printf '%s\n' "$commit" | grep -Eq '^[0-9a-f]{40}$'
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT HUP INT TERM
printf '%s\n' aarch64-apple-darwin x86_64-unknown-linux-gnu > "$work/targets"
: > "$work/expected"
while IFS= read -r target; do
  stem=game-screen-pick-$version-$target
  printf '%s\n' "$stem.tar.gz" "$stem.tar.gz.sha256" >> "$work/expected"
done < "$work/targets"
find "$destination" -mindepth 1 -maxdepth 1 -exec basename {} \; | LC_ALL=C sort > "$work/actual"
LC_ALL=C sort "$work/expected" > "$work/expected.sorted"
if ! cmp -s "$work/expected.sorted" "$work/actual"; then
  printf 'Release requires exactly both archives and their checksums\n' >&2; exit 1
fi
while IFS= read -r target; do
  stem=game-screen-pick-$version-$target
  archive=$destination/$stem.tar.gz
  checksum=$archive.sha256
  test -s "$archive"
  awk -v name="$stem.tar.gz" 'NF != 2 || length($1) != 64 || $1 ~ /[^0-9a-f]/ || $2 != name {bad=1} END {exit (bad || NR != 1)}' "$checksum"
  expected=$(awk '{print $1}' "$checksum")
  actual=$(shasum -a 256 "$archive" | awk '{print $1}')
  test "$actual" = "$expected"
  tar -tzf "$archive" > "$work/entries"
  # Archives are generated by this repository. Reject absolute/traversing paths,
  # links/devices, duplicate entries and a substituted top-level directory before
  # extraction of downloaded assets.
  awk -v root="$stem" '
    $0 != root && $0 != root "/" && index($0, root "/") != 1 {bad=1}
    /(^|\/)\.\.?($|\/)/ || /\/\// || /[[:space:]]/ {bad=1}
    seen[$0]++ {bad=1}
    END {exit (bad || NR == 0)}' "$work/entries"
  tar -tvzf "$archive" | awk 'substr($0,1,1) != "-" && substr($0,1,1) != "d" {bad=1} END {exit bad}'
  mkdir "$work/$target"
  tar -xzf "$archive" -C "$work/$target"
  root=$work/$target/$stem
  for file in bin/game-screen-pick BUILD-INFO.json DEPENDENCIES.txt LICENSE \
    config.example.toml README.md CONTRIBUTING.md assets/OFL.txt \
    licenses/NotoSansJP-OFL.txt licenses/THIRD-PARTY-LICENSES.txt licenses/dependencies.json \
    licenses/rust/COPYRIGHT.html licenses/rust/SOURCE-LICENSES.txt \
    docs/release.md docs/technical-reference.md docs/ai-client.md docs/brave-search.md \
    docs/acceptance.md docs/verification.md; do
    test -f "$root/$file" && test -s "$root/$file"
  done
  test -x "$root/bin/game-screen-pick"
  test -d "$root/docs"
  binary_sha256=$(shasum -a 256 "$root/bin/game-screen-pick" | awk '{print $1}')
  case "$target" in
    aarch64-apple-darwin) minimum_os='macOS 14.0' ;;
    x86_64-unknown-linux-gnu) minimum_os='Linux x86_64, glibc 2.35' ;;
  esac
  jq -e --arg version "$version" --arg target "$target" --arg commit "$commit" \
    --arg minimum_os "$minimum_os" --arg binary_sha256 "$binary_sha256" '
    .schema == 1 and .version == $version and .target == $target and
    .commit == $commit and .dirty == false and .minimum_os == $minimum_os and
    .binary_sha256 == $binary_sha256 and .external_commands == ["ffmpeg","ffprobe"] and
    (.rustc | type == "string" and length > 0) and (.cargo | type == "string" and length > 0)
  ' "$root/BUILD-INFO.json" > /dev/null
  jq -e 'type == "array" and length > 0 and all(.[];
    (.name | type == "string" and length > 0) and
    (.version | type == "string" and length > 0) and
    (.license | type == "string" and length > 0))' \
    "$root/licenses/dependencies.json" > /dev/null
done < "$work/targets"
printf 'Verified both target archives at %s (%s)\n' "$version" "$commit"
